import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import Ajv2020 from "ajv/dist/2020.js";
import addFormats from "ajv-formats";
import standalone from "ajv/dist/standalone/index.js";
import { _ } from "ajv";

// Only generate the consumed schema closure; reject unknown shapes and external references.
const source = readFileSync(
    new URL("../../../docs/api/openapi.json", import.meta.url),
);
const schema = JSON.parse(source);
const names = [
    "Health",
    "Identity",
    "Dashboard",
    "Activity",
    "CallPage",
    "Report",
    "JobStatus",
    "WorkspaceContext",
    "ModelVersionPage",
    "LiveConfig",
    "LivePeers",
    "LiveSessions",
    "LiveSessionView",
    "LiveTicket",
    "AudioReceipt",
    "LiveEvent",
    "TranscriptRevision",
    "FlushReceipt",
    "CallReviewView",
    "CallEnrollment",
    "CorrectionInput",
    "DecisionInput",
    "ConsentInput",
    "AnnotationDataset",
    "ReviewEventView",
];
for (const path of [
    "/health",
    "/ready",
    "/api/v1/me",
    "/api/v1/calls",
    "/api/v1/dashboard/activity",
    "/api/v1/model-versions",
]) {
    if (!schema.paths[path]?.get)
        throw new Error(`Missing GET contract: ${path}`);
}
const selected = {};
function typeOf(value) {
    if (value.$ref) {
        if (!/^#\/components\/schemas\/[A-Za-z0-9_]+$/.test(value.$ref))
            throw new Error("Unsupported reference");
        const name = value.$ref.split("/").at(-1);
        if (!names.includes(name)) names.push(name);
        return name;
    }
    if (value.anyOf) return "(" + value.anyOf.map(typeOf).join(" | ") + ")";
    if (value.enum) return value.enum.map((v) => JSON.stringify(v)).join(" | ");
    if ("const" in value) return JSON.stringify(value.const);
    if (value.type === "array") return `Array<${typeOf(value.items)}>`;
    if (value.type === "object") {
        if (!value.properties)
            return `Record<string, ${typeof value.additionalProperties === "object" ? typeOf(value.additionalProperties) : "unknown"}>`;
        return (
            "{\n" +
            Object.entries(value.properties)
                .map(
                    ([key, v]) =>
                        `  ${JSON.stringify(key)}${value.required?.includes(key) ? "" : "?"}: ${typeOf(v)};`,
                )
                .join("\n") +
            "\n}"
        );
    }
    if (["string", "boolean", "null"].includes(value.type)) return value.type;
    if (["integer", "number"].includes(value.type)) return "number";
    throw new Error("Unsupported schema shape");
}
const types = [];
for (let index = 0; index < names.length; index++) {
    const name = names[index];
    selected[name] = schema.components.schemas[name];
    if (!selected[name]) throw new Error(`Missing schema: ${name}`);
    types.push(`export type ${name} = ${typeOf(selected[name])};`);
}
const output = `// Generated by scripts/generate-api.mjs. Do not edit.\n// Canonical OpenAPI SHA256: ${createHash("sha256").update(JSON.stringify(schema)).digest("hex")}\n${types.join("\n\n")}\n`;
const target = new URL("../src/lib/api/generated.ts", import.meta.url);
const runtimeTarget = new URL(
    "../src/lib/api/schema.generated.json",
    import.meta.url,
);
const runtimeOutput =
    JSON.stringify({ components: { schemas: selected } }, null, 2) + "\n";
const validatorNames = [
    "Dashboard",
    "Activity",
    "CallPage",
    "Report",
    "JobStatus",
    "WorkspaceContext",
    "ModelVersionPage",
    "LiveConfig",
    "LivePeers",
    "LiveSessions",
    "LiveSessionView",
    "LiveTicket",
    "AudioReceipt",
    "LiveEvent",
    "TranscriptRevision",
    "FlushReceipt",
    "CallReviewView",
    "CallEnrollment",
    "CorrectionInput",
    "DecisionInput",
    "ConsentInput",
    "AnnotationDataset",
    "ReviewEventView",
];
const compiler = new Ajv2020({
    strict: false,
    inlineRefs: false,
    code: { source: true, esm: true, formats: _`formats` },
});
addFormats(compiler);
for (const name of validatorNames)
    compiler.addSchema({
        components: { schemas: selected },
        $id: name,
        $ref: `#/components/schemas/${name}`,
    });
const validationOutput =
    '// Generated by scripts/generate-api.mjs. Do not edit.\nimport { fullFormats as formats } from "ajv-formats/dist/formats.js";\nimport unicodeRuntime from "ajv/dist/runtime/ucs2length.js";\nconst unicodeLength = typeof unicodeRuntime === "function" ? unicodeRuntime : unicodeRuntime.default;\n' +
    standalone(
        compiler,
        Object.fromEntries(validatorNames.map((name) => [name, name])),
    ).replaceAll(
        'require("ajv/dist/runtime/ucs2length").default',
        "unicodeLength",
    ) +
    "\n";
if (/\brequire\(/.test(validationOutput))
    throw new Error(
        "A new validator runtime needs an explicit browser-safe ESM import",
    );
const validationTypes =
    "// Generated by scripts/generate-api.mjs. Do not edit.\n" +
    validatorNames
        .map(
            (name) =>
                `export declare function ${name}(data: unknown): boolean;`,
        )
        .join("\n") +
    "\n";
const validatorTarget = new URL(
    "../src/lib/api/validators.generated.mjs",
    import.meta.url,
);
const validatorTypesTarget = new URL(
    "../src/lib/api/validators.generated.d.mts",
    import.meta.url,
);
if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== output)
        throw new Error("API types are stale; run npm run api:generate");
    if (
        readFileSync(runtimeTarget, "utf8").replaceAll("\r\n", "\n") !==
        runtimeOutput
    )
        throw new Error("Runtime schemas are stale");
    if (
        readFileSync(validatorTarget, "utf8").replaceAll("\r\n", "\n") !==
            validationOutput ||
        readFileSync(validatorTypesTarget, "utf8").replaceAll("\r\n", "\n") !==
            validationTypes
    )
        throw new Error("Standalone validators are stale");
} else {
    writeFileSync(target, output);
    writeFileSync(runtimeTarget, runtimeOutput);
    writeFileSync(validatorTarget, validationOutput);
    writeFileSync(validatorTypesTarget, validationTypes);
}
